"""BM25 가 쓸 한국어 토크나이저.

## 왜 형태소 분석기가 아닌가

조사가 붙으면 낱말이 달라진다 — `시행령은` 과 `시행령` 은 공백으로 자르면 다른 토큰이라
BM25 가 못 잇는다. 정공법은 형태소 분석기지만 새 의존성이고, 설치가 안 되는 환경에서
*기본 `pytest` 는 키 없이 전부 통과* 가 위협받는다. **어느 쪽이 나은지는 아직 안 쟀다** —
`plan_log/검색-생성.md` 2회차의 미결이고 정답 세트로 잴 수 있다.

대신 **문자 bigram** 을 쓴다. `시행령은` → `시행`·`행령`·`령은` 이라 `시행령` → `시행`·`행령`
과 두 토큰을 공유해, 조사 문제에 **규칙 없이 구조적으로** 강하다. 조사 목록을 우리가
지어내지 않는 것이 요점이다 — 지어낸 목록은 틀려도 아무도 안 알려준다.

## 왜 영문·숫자는 bigram 이 아닌가

**공백으로 낱말이 갈리느냐가 축이다.** 한글·한자는 낱글자가 뜻을 갖고 공백이 낱말 경계를
보장하지 않지만, 영문·숫자는 공백이 이미 낱말을 갈라 준다. 전부 bigram 으로 자르면 긴
영단어가 잡음 토큰을 쏟아내고, 반대로 `AI` 같은 두 글자 약어는 얻는 것이 없다.

**이것은 임계값이 아니라 이분법이라 분포의 틈을 고를 필요가 없다.** 쪽 경계 판정을
*한글을 가진 텍스트 블록이 0개인가* 로 고른 것과 같은 모양이다(CLAUDE.md).

## 감수 사항

- 경계 문자는 통째로 버린다. `DNA+` 는 `dna` 가 되고 `+` 는 사라진다
- 한글 자모(`ㄱ`·`ㅏ`)는 경계다. 음절로 조합되지 않은 낱자는 이 코퍼스(공문서)에 사실상 없다
- bigram 은 색인을 키운다. 청크 수백 개 규모에서는 문제가 안 되고, 커지면 그때 잰다
"""

from __future__ import annotations

import re

__all__ = ["tokenize"]

# 두 갈래를 한 번에 훑는다. 어느 쪽에도 안 걸리는 문자는 그대로 경계가 된다.
# 앞은 공백이 낱말을 갈라 주는 문자, 뒤는 낱글자가 뜻을 갖는 문자(한글 음절·한자)다
_RUN = re.compile(r"([A-Za-z0-9]+)|([가-힣一-鿿]+)")


# 낱글자 문자열을 bigram 으로. 한 글자면 그 글자가 유일한 토큰이다 —
# 빈 리스트를 돌려주면 `표`·`장` 같은 한 글자 낱말이 색인에서 통째로 사라진다
def _bigrams(run: str) -> list[str]:
    if len(run) == 1:
        return [run]
    return [run[i : i + 2] for i in range(len(run) - 1)]


# 텍스트를 BM25 토큰 목록으로. 질의와 문서에 **같은 함수를 쓴다** —
# 갈라 두면 한쪽만 고쳤을 때 검색이 조용히 0건이 된다
def tokenize(text: str) -> list[str]:
    tokens: list[str] = []
    for word, syllabic in _RUN.findall(text):
        if word:
            tokens.append(word.lower())
        else:
            tokens.extend(_bigrams(syllabic))
    return tokens
